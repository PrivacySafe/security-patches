# Donate: https://privacysafe.foundation/donate
#
#   packaging/report-logo.py --write    convert packaging/site/img/privacysafe-logo.svg and write it into psf-report.py
#   packaging/report-logo.py --check    exit 1 if the embedded logo differs from what the SVG gives now
#
# psf-report needs nothing but Python 3 on the host it runs on, so the logo travels inside it: the SVG itself,
# compacted, for HTML reports, and PDF drawing data for PDF reports. The converter handles what the logo uses:
# paths with M, L, H, V, C, Q and Z (absolute and relative; a quadratic curve becomes the equal cubic one),
# group transforms (translate, matrix), solid fills and linear gradients in user space. Anything else stops it.
import os
import re
import sys
import tempfile
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SVG = os.path.join(ROOT, "packaging", "site", "img", "privacysafe-logo.svg")
REPORT = os.path.join(ROOT, "automation", "psf-report.py")
BEGIN = "# ---- logo begin (generated by packaging/report-logo.py from packaging/site/img/privacysafe-logo.svg; do not edit) ----"
END = "# ---- logo end ----"
NS = "{http://www.w3.org/2000/svg}"
NUM = re.compile(r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?")


def fmt(v):
    s = "%.2f" % v
    s = s.rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def hex_rgb(h):
    h = h.lstrip("#")
    return tuple(round(int(h[i:i + 2], 16) / 255.0, 4) for i in (0, 2, 4))


def path_ops(d):
    """PDF path construction operators for SVG path data."""
    toks = re.findall(r"[MmLlHhVvCcQqZz]|" + NUM.pattern, d)
    out, i, cmd = [], 0, None
    x = y = sx = sy = 0.0

    def num():
        nonlocal i
        v = float(toks[i])
        i += 1
        return v

    while i < len(toks):
        t = toks[i]
        if re.fullmatch(r"[A-Za-z]", t):
            cmd = t
            i += 1
            if cmd in "Zz":
                out.append("h")
                x, y = sx, sy
                continue
        elif cmd is None:
            raise SystemExit("path data starts with a number")
        rel = cmd.islower()
        c = cmd.upper()
        if c == "M":
            nx, ny = num(), num()
            x, y = (x + nx, y + ny) if rel else (nx, ny)
            sx, sy = x, y
            out.append("%s %s m" % (fmt(x), fmt(y)))
            cmd = "l" if rel else "L"          # pairs after a move are lines
        elif c == "L":
            nx, ny = num(), num()
            x, y = (x + nx, y + ny) if rel else (nx, ny)
            out.append("%s %s l" % (fmt(x), fmt(y)))
        elif c == "H":
            nx = num()
            x = x + nx if rel else nx
            out.append("%s %s l" % (fmt(x), fmt(y)))
        elif c == "V":
            ny = num()
            y = y + ny if rel else ny
            out.append("%s %s l" % (fmt(x), fmt(y)))
        elif c == "C":
            p = [num() for _ in range(6)]
            if rel:
                p = [p[0] + x, p[1] + y, p[2] + x, p[3] + y, p[4] + x, p[5] + y]
            out.append(" ".join(fmt(v) for v in p) + " c")
            x, y = p[4], p[5]
        elif c == "Q":
            p = [num() for _ in range(4)]
            if rel:
                p = [p[0] + x, p[1] + y, p[2] + x, p[3] + y]
            qx, qy, ex, ey = p
            c1 = (x + 2.0 / 3.0 * (qx - x), y + 2.0 / 3.0 * (qy - y))
            c2 = (ex + 2.0 / 3.0 * (qx - ex), ey + 2.0 / 3.0 * (qy - ey))
            out.append(" ".join(fmt(v) for v in (c1[0], c1[1], c2[0], c2[1], ex, ey)) + " c")
            x, y = ex, ey
        else:
            raise SystemExit("unsupported path command: " + cmd)
    return " ".join(out)


def matrix_of(t):
    if not t:
        return (1, 0, 0, 1, 0, 0)
    m = re.fullmatch(r"\s*translate\(([^)]*)\)\s*", t)
    if m:
        v = [float(n) for n in NUM.findall(m.group(1))] + [0.0]
        return (1, 0, 0, 1, v[0], v[1])
    m = re.fullmatch(r"\s*matrix\(([^)]*)\)\s*", t)
    if m:
        v = [float(n) for n in NUM.findall(m.group(1))]
        if len(v) == 6:
            return tuple(v)
    raise SystemExit("unsupported transform: " + t)


def convert():
    raw = open(SVG, encoding="utf-8").read()
    root = ET.fromstring(raw)
    vb = [float(n) for n in NUM.findall(root.get("viewBox"))]
    grads = {}
    for g in root.iter(NS + "linearGradient"):
        if g.get("gradientUnits") != "userSpaceOnUse":
            raise SystemExit("gradient %s is not in user space" % g.get("id"))
        stops = [s.get("stop-color") for s in g.findall(NS + "stop")]
        if len(stops) != 2:
            raise SystemExit("gradient %s needs two stops" % g.get("id"))
        grads[g.get("id")] = (float(g.get("x1")), float(g.get("y1")), float(g.get("x2")), float(g.get("y2")),
                              hex_rgb(stops[0]), hex_rgb(stops[1]))
    parts = []

    def walk(el, matrix, fill):
        for ch in el:
            tag = ch.tag.replace(NS, "")
            if tag in ("title", "defs", "desc"):
                continue
            f = ch.get("fill") or fill
            if tag == "g":
                if ch.get("transform") and matrix != (1, 0, 0, 1, 0, 0):
                    raise SystemExit("nested transforms are not supported")
                walk(ch, matrix_of(ch.get("transform")), f)
            elif tag == "path":
                if ch.get("transform") or ch.get("fill-rule") or ch.get("style"):
                    raise SystemExit("unsupported path attribute")
                m = re.fullmatch(r"url\(#([^)]+)\)", f or "")
                if m:
                    x1, y1, x2, y2, c0, c1 = grads[m.group(1)]
                    paint = ("grad", (round(x1, 2), round(y1, 2), round(x2, 2), round(y2, 2)), c0, c1)
                elif f and f.startswith("#"):
                    paint = ("solid", hex_rgb(f))
                else:
                    raise SystemExit("unsupported fill: %r" % f)
                parts.append((tuple(round(v, 6) for v in matrix), path_ops(ch.get("d")), paint))
            else:
                raise SystemExit("unsupported element: " + tag)

    walk(root, (1, 0, 0, 1, 0, 0), None)
    compact = re.sub(r">\s+<", "><", raw.strip())
    compact = re.sub(r"<title>[^<]*</title>", "", compact)
    compact = compact.replace(' role="img" aria-label="PrivacySafe"', ' role="img" aria-label="PrivacySafe" class="ps-logo"', 1)
    return vb, parts, compact


def block():
    vb, parts, compact = convert()
    lines = [BEGIN,
             "LOGO_VIEWBOX = (%s, %s)" % (fmt(vb[2]), fmt(vb[3])),
             "LOGO_SVG = %r" % compact,
             "LOGO_PARTS = ["]
    for matrix, ops, paint in parts:
        lines.append("    (%r, %r," % (matrix, ops))
        lines.append("     %r)," % (paint,))
    lines += ["]", END]
    return "\n".join(lines)


def main(argv):
    if len(argv) != 2 or argv[1] not in ("--write", "--check"):
        print("usage: report-logo.py --write | --check", file=sys.stderr)
        return 2
    text = open(REPORT, encoding="utf-8").read()
    if BEGIN not in text or END not in text:
        print("psf-report.py has no logo block markers", file=sys.stderr)
        return 2
    a = text.index(BEGIN)
    b = text.index(END) + len(END)
    new = text[:a] + block() + text[b:]
    if argv[1] == "--check":
        if new != text:
            print("the logo embedded in automation/psf-report.py is out of date: run packaging/report-logo.py --write")
            return 1
        print("the embedded logo matches packaging/site/img/privacysafe-logo.svg")
        return 0
    if new != text:
        fd, tmp = tempfile.mkstemp(prefix=".psf-report.", suffix=".tmp", dir=os.path.dirname(REPORT))
        with os.fdopen(fd, "w", encoding="utf-8") as f:   # a new file of its own: never a planted link
            f.write(new)
        os.chmod(tmp, os.stat(REPORT).st_mode & 0o7777)
        os.replace(tmp, REPORT)
    print("logo written into automation/psf-report.py (%d parts)" % len(convert()[1]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

