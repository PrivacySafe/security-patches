#!/usr/bin/env python3
# SPDX-License-Identifier: CC0-1.0
# =============================================================================
# rhsa.py: find Red Hat security advisories, check installed packages against
# them, and keep the Red Hat sections of the PrivacySafe Security Patches
# READMEs up to date
#
# If this software is helpful, consider a donation to our 501c3 nonprofit:
# https://privacysafe.foundation
#
# Red Hat publishes a security advisory (RHSA) for each fix it ships. Given Red Hat's
# list of advisories (a CSV or JSON file with one record per advisory: release date,
# RHSA, severity, CVEs and packages) this tool answers four questions.
#
#   rhsa.py find CVE... [--list FILE | --index FILE] [--stream 9.6] [--package kernel] [--json]
#       Which advisories name this CVE, for which RHEL stream, and which package release fixes it?
#   rhsa.py verify [NEVRA... | -] [--rpm [PKG...]] [--cve CVE]... [--all] [--list FILE]
#       Is this installed package at or after Red Hat's fix? NEVRA is name-[epoch:]version-release[.arch],
#       from rpm -qa, one per line on standard input with "-", or read from rpm itself with --rpm. --list FILE
#       checks against a list downloaded with fetch, for every CVE in it, instead of the shipped index.
#       Exit 1 when a package is older than a fix.
#   rhsa.py index LIST [PAIRS] [--repo DIR] [--cve CVE]... [--all] [--out FILE]
#       Build the small index this tool works from: the advisories of the CVEs the repository's
#       READMEs name (and those in placement.json). PAIRS, Red Hat's list of advisory and CVE
#       pairs, is optional: the CVEs are read from LIST, and PAIRS is only compared with them.
#   rhsa.py docs --repo DIR (--write | --check)
#       Write a "Red Hat advisories" section into each README that placement.json names, and the index
#       document REDHAT-ADVISORIES.md; or list what is out of date.
#   rhsa.py audit --repo DIR
#       Check the repository against the index: sections up to date, every CVE with an advisory placed or
#       excluded on purpose, every advisory id cited anywhere really in the data. Exit 1 on a problem.
#   rhsa.py fetch --after YYYY-MM-DD --out LIST.json [--merge LIST.json]
#       Download Red Hat's list from its Security Data API (the only command that uses the network);
#       find --live CVE asks the same API for one CVE. Both can be pointed at another server with --url.
#   rhsa.py stats [--index FILE]     what the index holds
#
# A Red Hat build is judged by its RPM release, not by the upstream version, because Red Hat backports
# fixes. verify compares releases the way rpm does (rpmvercmp). It reads the stream of a package from its
# release (el9_6 is RHEL 9.6), so a stream that has no advisory in the list is reported, never guessed.
# A CVE with no advisory in the list has none for that period: that is not the same as not affected.
# The list holds security advisories only (RHSA), not bug fixes or enhancements.
#
# Needs Python 3.8 or newer and nothing else. Only fetch and find --live use the network.
#
# Assisted-by: Claude Sonnet 5.5
# =============================================================================
