def cmd_index(a):
    adv = read_list(a.list)
    plc, _ = load_placement(a.placement)
    wanted = None if a.all else placed_cves(plc) | set(a.cve or [])
    if a.repo and wanted is not None:
        wanted |= repo_cves(a.repo)
    idx = build_index(adv, wanted, "Red Hat security advisories (RHSA), %s" % os.path.basename(a.list))
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w", encoding="utf-8") as fh:
        json.dump(idx, fh, separators=(",", ":"), sort_keys=True, ensure_ascii=False)
        fh.write("\n")
    print(
        "index: %s have an advisory in the list (%d advisories, %s to %s) -> %s"
        % (
            "all %d CVEs" % len(idx["cves"]) if wanted is None else "%d of %d CVEs" % (len(idx["cves"]), len(wanted)),
            idx["meta"]["advisories"],
            idx["meta"]["first"],
            idx["meta"]["last"],
            a.out,
        )
    )
    if a.pairs:
        pairs = read_pairs(a.pairs)
        derived = collections.defaultdict(set)
        for r, x in adv.items():
            for c in x["cves"]:
                derived[c].add(r)
        bad = sum(1 for c in set(pairs) | set(derived) if pairs.get(c, set()) != derived.get(c, set()))
        print(
            "pairs file: %s (%d CVEs differ)" % ("agrees with the list" if not bad else "DISAGREES with the list", bad)
        )
        return 1 if bad else 0
    return 0


def cmd_docs(a):
    idx = load_index(a.index)
    plc, _ = load_placement(a.placement)
    stale = []
    for p in plc:
        if apply_block(os.path.join(a.repo, p), section(p, plc, idx), a.check):
            stale.append(p)
    d = os.path.join(a.repo, "REDHAT-ADVISORIES.md")
    new = document(idx, plc)
    if not os.path.exists(d) or open(d, encoding="utf-8").read() != new:
        stale.append("REDHAT-ADVISORIES.md")
        if not a.check:
            open(d, "w", encoding="utf-8").write(new)
    if a.check:
        for s in stale:
            print("not up to date:", s)
        print("%d file(s) not up to date" % len(stale))
        return 1 if stale else 0
    print("written: %d file(s) changed" % len(stale))
    return 0


def cmd_audit(a):
    idx = load_index(a.index)
    plc, raw = load_placement(a.placement)
    problems = []
    excluded = set(raw.get("_excluded", []))
    outside = set(raw.get("_known_outside_window", []))
    for p in plc:
        path = os.path.join(a.repo, p)
        text = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        if not BEGIN_RE.search(text) or END not in text:
            problems.append("%s: no Red Hat advisories block" % p)
            continue
        blk = text[BEGIN_RE.search(text).start() : text.index(END)]
        for c in set(plc[p].get("cves", [])) | set(plc[p].get("summary", [])) | set(plc[p].get("point", {})):
            if (
                c in idx["cves"]
                and c not in blk
                and not (plc[p].get("matrix") and ("| " + c.replace("CVE-2026-", "") + " ") in blk)
            ):
                problems.append("%s: %s has advisories but is not in its block" % (p, c))
    for rel in readmes(a.repo):
        named = {
            c
            for c in re.findall(r"CVE-\d{4}-\d{4,7}", open(os.path.join(a.repo, rel), encoding="utf-8").read())
            if c in idx["cves"]
        }
        if named and rel not in plc and rel not in excluded:
            problems.append(
                "%s: names %s, which have advisories, but is neither placed nor excluded in placement.json"
                % (rel, ", ".join(sorted(named)[:3]))
            )
    known = set(idx["advisories"]) | outside
    for dp, dn, fn in os.walk(a.repo):
        if any(x in dp for x in SKIP_DIRS):
            continue
        for f in fn:
            if f.endswith((".md", ".sh", ".py")):
                rel = os.path.relpath(os.path.join(dp, f), a.repo)
                for r in sorted(set(re.findall(r"RHSA-\d{4}:\d+", open(os.path.join(dp, f), errors="replace").read()))):
                    if r not in known:
                        problems.append("%s: cites %s, which is not in the data" % (rel, r))
    stale = io_call(cmd_docs, argparse.Namespace(repo=a.repo, index=a.index, placement=a.placement, check=True))
    if stale:
        problems.append("the sections or REDHAT-ADVISORIES.md are out of date (rhsa.py docs --write)")
    for p in problems:
        print("problem:", p)
    print(
        "audit: %d problem(s); %d advisories for %d CVEs in the index"
        % (len(problems), len(idx["advisories"]), len(idx["cves"]))
    )
    return 1 if problems else 0


def io_call(fn, ns):
    import contextlib
    import io

    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        return fn(ns)


def stream_arg(s):
    s = s.strip()
    return s if s.upper().startswith("RHEL") else "RHEL " + s


def cmd_fetch(a):
    adv = fetch_list(a.url, a.after, a.before, per_page=a.per_page)
    if a.merge and os.path.exists(a.merge):
        old = read_list(a.merge)
        old.update(adv)
        adv = old
    write_list(a.out, adv)
    ds = sorted(x["date"] for x in adv.values())
    print(
        "fetched: %d advisories (%s to %s) -> %s" % (len(adv), ds[0], ds[-1], a.out)
        if adv
        else "fetched: no advisories"
    )
    return 0 if adv else 1


def cmd_find(a):
    if a.live:
        adv = {}
        for c in a.cve:
            adv.update(fetch_list(a.url, cve=c))
        idx = build_index(adv, set(a.cve), "Red Hat Security Data API")
    elif a.list:
        adv = read_list(a.list)
        idx = build_index(adv, set(a.cve), os.path.basename(a.list))
    else:
        idx = load_index(a.index)
    out = {}
    for c in a.cve:
        rs = recs(idx, c)
        if a.stream:
            want = stream_arg(a.stream)
            rs = [r for r in rs if any(i["stream"] == want or i["stream"].startswith(want + " ") for i in r["items"])]
        if a.package:
            rs = [
                r
                for r in rs
                if any(re.search(a.package, i["name"]) for i in r["items"])
                or any(re.search(a.package, n) for n in r["names"])
            ]
        out[c] = rs
    if a.json:
        print(json.dumps(out, indent=1, ensure_ascii=False))
        return 0 if any(out.values()) else 1
    for c, rs in out.items():
        print(
            "%s: %s"
            % (
                c,
                (
                    plural(len(rs), "advisory", "advisories")
                    if rs
                    else "no advisory in the list (%s to %s); that is not the same as not affected"
                    % (idx["meta"]["first"], idx["meta"]["last"])
                ),
            )
        )
        for r in rs:
            its = [
                i
                for i in r["items"]
                if (not a.package or re.search(a.package, i["name"]))
                and (
                    not a.stream
                    or i["stream"] == stream_arg(a.stream)
                    or i["stream"].startswith(stream_arg(a.stream) + " ")
                )
            ] or r["items"]
            for i in its[: a.limit]:
                full = "%s-%s-%s" % (i["name"], i["ver"], i["rel"]) if i["ver"] else i["name"]
                print("  %-16s %s  %-9s %-18s %s" % (r["rhsa"], r["date"], sev(r["severity"]), i["stream"], full))
            if len(its) > a.limit:
                print("  %-16s ... and %d more packages" % ("", len(its) - a.limit))
    return 0 if any(out.values()) else 1


def kernel_alias(name):
    if name.startswith("kernel-rt"):
        return "kernel-rt"
    return "kernel" if name.startswith("kernel-") else name


def pick_item(items, name):
    """The source package of an advisory that an installed (binary) package belongs to, or None."""
    if len(items) == 1:
        return items[0]
    for key in (name, kernel_alias(name)):
        for i in items:
            if i["name"] == key:
                return i
    pre = [i for i in items if name.startswith(i["name"] + "-")]
    return max(pre, key=lambda i: len(i["name"])) if pre else None


def family(stream, rel):
    """The stream, plus the OpenShift release when the build names one.

    rhaos4.18 and rhaos4.21 are different products.
    """
    m = re.search(r"rhaos\d+\.\d+", rel or "")
    return stream + (" " + m.group(0) if m else "")


def line(ver):
    """The version line of a package: 5.14 for 5.14.0, 8.2 for 8.2.28. Versions are comparable only within one line."""
    m = re.match(r"(\d+)\.(\d+)", ver or "")
    return m.group(0) if m else ver


def few(items, n=3, sep=", "):
    items = list(items)
    return sep.join(items[:n]) + (" and %d more" % (len(items) - n) if len(items) > n else "")


def plural(n, one, many=None):
    return "%d %s" % (n, one if n == 1 else (many or one + "s"))


def verify_one(idx, nevra, only, maxsrc=MAX_SRC):
    p = parse_pkg(nevra)
    if not p["ver"]:
        return "UNREADABLE", "cannot read name-version-release from %r" % nevra, False
    name = p["name"]
    cand = [
        r
        for r in idx["advisories"]
        if name in idx["advisories"][r]["names"] or kernel_alias(name) in idx["advisories"][r]["names"]
    ]
    cand = [r for r in cand if not only or set(idx["advisories"][r]["cves"]) & only]
    if not cand:
        return "NOT LISTED", "no advisory in the list names %s" % name, False
    streams = sorted({family(i["stream"], i["rel"]) for r in cand for i in idx["advisories"][r]["items"]}, key=skey)
    mine = family(p["stream"], p["rel"])
    fixes, ambiguous, bundles, otherline = {}, False, [], set()
    for r in cand:
        a = idx["advisories"][r]
        if len(a["items"]) > maxsrc:
            bundles.append(r)
            continue  # a bundle does not say which package fixes which CVE
        same = [i for i in a["items"] if family(i["stream"], i["rel"]) == mine]
        if not same:
            continue
        item = pick_item(same, name)
        if not item:
            ambiguous = True
            continue
        if line(item["ver"]) != line(p["ver"]):
            otherline.add(item["ver"])
            continue  # another version line (php 8.0 against 8.2): a higher number proves nothing
        for c in a["cves"]:
            if only and c not in only:
                continue
            cur = fixes.get(c)
            if (
                cur is None
                or evr_cmp(item["epoch"], item["ver"], item["rel"], cur[1]["epoch"], cur[1]["ver"], cur[1]["rel"]) < 0
            ):
                fixes[c] = (r, item)
    if not fixes:
        if bundles and not ambiguous and len(bundles) == len(cand):
            return (
                "CHECK BY HAND",
                "only advisories that list more than %d packages name %s (%s); they do not say which package fixes "
                "which CVE" % (maxsrc, name, few(bundles, 2)),
                False,
            )
        if otherline:
            return (
                "CHECK BY HAND",
                "the advisories for %s are for other version lines of %s (%s), not for %s: a release on another "
                "line cannot be compared" % (mine, name, few(sorted(otherline)), line(p["ver"])),
                False,
            )
        if ambiguous:
            return (
                "CHECK BY HAND",
                "an advisory for %s covers several source packages and none is %s" % (mine, name),
                False,
            )
        return (
            "NO ADVISORY FOR STREAM",
            "advisories name %s, but none for %s; they are for %s" % (name, mine, few(streams, 6)),
            False,
        )
    old = {
        c: v
        for c, v in fixes.items()
        if evr_cmp(p["epoch"] or v[1]["epoch"], p["ver"], p["rel"], v[1]["epoch"], v[1]["ver"], v[1]["rel"]) < 0
    }
    if old:
        worst = max(old.values(), key=lambda v: (v[1]["ver"], v[1]["rel"]))[1]
        return (
            "VULNERABLE",
            "%s: older than %s-%s-%s, which fixes %s (%s)"
            % (
                mine,
                worst["name"],
                worst["ver"],
                worst["rel"],
                few(sorted(old)),
                few(sorted({v[0] for v in old.values()})),
            ),
            True,
        )
    return (
        "FIXED",
        "%s: at or after the fix for %s (%s)" % (mine, few(sorted(fixes)), few(sorted({v[0] for v in fixes.values()}))),
        False,
    )


def cmd_verify(a):
    idx = build_index(read_list(a.list), None, os.path.basename(a.list)) if a.list else load_index(a.index)
    only = set(a.cve or [])
    pk_args = list(a.nevra)
    if a.rpm is not None:
        fmt = "%{NAME}-%{EPOCHNUM}:%{VERSION}-%{RELEASE}.%{ARCH}\n"
        cmd = ["rpm", "-q", "--qf", fmt] + a.rpm if a.rpm else ["rpm", "-qa", "--qf", fmt]
        try:
            pk_args += [
                x
                for x in subprocess.run(cmd, capture_output=True, text=True).stdout.split("\n")
                if x.strip() and "is not installed" not in x
            ]
        except FileNotFoundError:
            sys.exit("rhsa.py: rpm is not installed here; give the package names (NEVRA) instead")
    if pk_args == ["-"] or (not pk_args and not sys.stdin.isatty() and a.rpm is None):
        pk_args = [x.strip() for x in sys.stdin.read().split("\n") if x.strip()]
    if not pk_args:
        sys.exit("rhsa.py verify: give package names, - for standard input, or --rpm")
    bad = 0
    for n in pk_args:
        verdict, why, vuln = verify_one(idx, n, only, a.max_packages)
        bad += vuln
        if verdict == "NOT LISTED" and not a.all:
            continue
        print("%-22s %s  %s" % (verdict, n, why))
    print(
        "verified %d package(s): %d older than a Red Hat fix. A listed fix is a fact about the release; whether "
        "the flaw is reachable on your host is another question." % (len(pk_args), bad)
    )
    return 1 if bad else 0


def cmd_stats(a):
    idx = load_index(a.index)
    m = idx["meta"]
    sv = collections.Counter(x["severity"] for x in idx["advisories"].values())
    st = collections.Counter(i["stream"] for x in idx["advisories"].values() for i in x["items"][:1])
    print(
        "list: %d advisories for %d CVEs, %s to %s (%s)"
        % (m["advisories"], m["cves"], m["first"], m["last"], m["source"])
    )
    print(
        "index: %d advisories for %d CVEs; severity %s"
        % (len(idx["advisories"]), len(idx["cves"]), dict(sv.most_common()))
    )
    print("streams: " + ", ".join("%s %d" % (k, n) for k, n in sorted(st.items(), key=lambda kv: skey(kv[0]))))
    return 0


