# ---------- reading the list --------------------------------------------------------------------------
def read_list(path):
    """Red Hat's list (CSV or JSON) -> {RHSA: {date, severity, cves, packages}}."""
    if path.endswith(".json"):
        rows = json.load(open(path, encoding="utf-8"))
    else:
        rows = list(csv.DictReader(open(path, encoding="utf-8-sig", newline="")))
    out = {}
    for r in rows:
        cves = [c for c in re.split(r"[,;\s]+", r.get("CVEs") or "") if c]
        out[r["RHSA"].strip()] = dict(
            date=r["Release Date"].strip(),
            severity=(r.get("Severity") or "").strip().lower(),
            cves=cves,
            packages=r.get("Packages") or "",
        )
    if not out:
        sys.exit("rhsa.py: no advisories in " + path)
    return out


def fetch_list(url=API, after=None, before=None, cve=None, per_page=1000):
    """Red Hat's Security Data API -> the same {RHSA: record} as read_list. The one place the tool uses the network."""
    out, page = {}, 1
    while True:
        q = {"per_page": per_page, "page": page}
        for k, v in (("after", after), ("before", before), ("cve", cve)):
            if v:
                q[k] = v
        got = None
        for attempt in range(3):
            try:
                req = urllib.request.Request(
                    url + "?" + urllib.parse.urlencode(q), headers={"User-Agent": "rhsa.py/" + VERSION}
                )
                got = json.load(urllib.request.urlopen(req, timeout=60))
                break
            except Exception as e:
                if attempt == 2:
                    sys.exit("rhsa.py: cannot fetch %s: %s" % (url, e))
                time.sleep(2 * (attempt + 1))
        for r in got:
            if str(r.get("RHSA", "")).startswith("RHSA-"):
                out[r["RHSA"]] = dict(
                    date=str(r.get("released_on", ""))[:10],
                    severity=str(r.get("severity", "")).lower(),
                    cves=list(r.get("CVEs") or []),
                    packages="; ".join(r.get("released_packages") or []),
                )
        if len(got) < per_page:
            return out
        page += 1


def write_list(path, adv):
    rows = [
        {
            "Release Date": a["date"],
            "RHSA": r,
            "Severity": a["severity"],
            "Synopsis": "",
            "CVE Count": len(a["cves"]),
            "CVEs": ", ".join(a["cves"]),
            "Packages": a["packages"],
            "Advisory URL": ERRATA + r,
            "CSAF URL": "https://access.redhat.com/hydra/rest/securitydata/csaf/%s.json" % r,
        }
        for r, a in sorted(adv.items(), key=lambda kv: (kv[1]["date"], kv[0]), reverse=True)
    ]
    json.dump(rows, open(path, "w", encoding="utf-8"), ensure_ascii=False)


def read_pairs(path):
    pairs = collections.defaultdict(set)
    for r in csv.DictReader(open(path, encoding="utf-8-sig", newline="")):
        pairs[r["CVE"].strip()].add(r["RHSA"].strip())
    return pairs


# ---------- package names ------------------------------------------------------------------------------
def parse_pkg(entry):
    """name-[epoch:]version-release[.arch] (or a Hummingbird, module or container form) -> a dict."""
    e = entry.strip()
    if e.startswith("registry.") or "@sha256:" in e:
        name = e.split("@sha256")[0].split("/", 1)[-1]
        return dict(name=name, epoch="0", ver="", rel="", stream="container image", kind="image", src=True)
    if "::" in e:
        e = e.split("::", 1)[0]
    arch = ""
    if "@" in e:
        parts = e.split("@")
        e = parts[0]
        arch = parts[1] if len(parts) > 1 else ""
    m = re.match(r"^(.+?)-(?:(\d+):)?(\d[^-]*)-(.+?)(?:\.(" + ARCH + r"))?$", e)
    if not m:
        return dict(name=e, epoch="0", ver="", rel="", stream="Red Hat", kind="rpm", src=False)
    name, epoch, ver, rel, a = m.groups()
    arch = a or arch
    if name.startswith("kpatch-patch"):
        name = "kpatch-patch"
    return dict(
        name=name,
        epoch=epoch or "",
        ver=ver,
        rel=rel,
        stream=stream_of(name, rel, entry),
        kind="rpm",
        src=(arch == "src"),
    )


def stream_of(name, rel, entry=""):
    if name.startswith("rhcos"):
        return "OpenShift (RHCOS)"
    if "hum" in rel:
        return "Hummingbird"
    x = re.search(r"\.el(\d+)([a-z][a-z0-9]*)$", rel)
    if x:
        return "RHEL %s (el%s%s)" % (x.group(1), x.group(1), x.group(2))
    x = re.search(r"el(\d+)_(\d+)", rel)
    if x:
        return "RHEL %s.%s" % (x.group(1), x.group(2))
    x = re.search(r"module\+el(\d+)\.(\d+)", entry or rel)
    if x:
        return "RHEL %s.%s" % (x.group(1), x.group(2))
    x = re.search(r"\.el(\d+)", rel)
    if x:
        return "RHEL %s" % x.group(1)
    if "openshift" in name or "rhaos" in rel:
        return "OpenShift"
    return "Red Hat"


def rpmvercmp(a, b):
    """rpm's version comparison: -1, 0 or 1."""
    if a == b:
        return 0
    i = j = 0
    la, lb = len(a), len(b)

    def sep(ch):
        return not (ch.isalnum() and ch.isascii()) and ch not in "~^"

    while i < la or j < lb:
        while i < la and sep(a[i]):
            i += 1
        while j < lb and sep(b[j]):
            j += 1
        if (i < la and a[i] == "~") or (j < lb and b[j] == "~"):
            if not (i < la and a[i] == "~"):
                return 1
            if not (j < lb and b[j] == "~"):
                return -1
            i += 1
            j += 1
            continue
        if (i < la and a[i] == "^") or (j < lb and b[j] == "^"):
            if i >= la:
                return -1
            if j >= lb:
                return 1
            if a[i] != "^":
                return 1
            if b[j] != "^":
                return -1
            i += 1
            j += 1
            continue
        if not (i < la and j < lb):
            break
        si, sj = i, j
        if a[i].isdigit():
            while i < la and a[i].isdigit():
                i += 1
            while j < lb and b[j].isdigit():
                j += 1
            isnum = True
        else:
            while i < la and a[i].isalpha() and a[i].isascii():
                i += 1
            while j < lb and b[j].isalpha() and b[j].isascii():
                j += 1
            isnum = False
        sa, sb = a[si:i], b[sj:j]
        if not sb:
            return 1 if isnum else -1
        if isnum:
            sa, sb = sa.lstrip("0"), sb.lstrip("0")
            if len(sa) != len(sb):
                return 1 if len(sa) > len(sb) else -1
        if sa != sb:
            return 1 if sa > sb else -1
    if i >= la and j >= lb:
        return 0
    return -1 if i >= la else 1


def evr_cmp(e1, v1, r1, e2, v2, r2):
    for x, y in ((e1 or "0", e2 or "0"), (v1, v2), (r1, r2)):
        c = rpmvercmp(x, y)
        if c:
            return c
    return 0


# ---------- the index ------------------------------------------------------------------------------------
def build_index(adv, wanted, source=""):
    advisories, cves = {}, collections.defaultdict(list)
    for rhsa, a in adv.items():
        ours = sorted(c for c in set(a["cves"]) if wanted is None or c in wanted)
        if not ours:
            continue
        entries = [parse_pkg(x) for x in a["packages"].split(";") if x.strip()]
        src = [i for i in entries if i["src"]] or entries
        seen, items = set(), []
        for i in src:
            k = (i["name"], i["epoch"], i["ver"], i["rel"])
            if k not in seen:
                seen.add(k)
                items.append({f: i[f] for f in ("name", "epoch", "ver", "rel", "stream", "kind")})
        names = sorted({i["name"] for i in entries if i["kind"] == "rpm"})
        advisories[rhsa] = dict(date=a["date"], severity=a["severity"], cves=ours, items=items, names=names)
        for c in ours:
            cves[c].append(rhsa)
    for c in cves:
        cves[c].sort(key=lambda r: (advisories[r]["date"], r))
    dates = sorted(a["date"] for a in adv.values())
    every = {c for a in adv.values() for c in a["cves"]}
    return {
        "meta": {
            "advisories": len(adv),
            "cves": len(every),
            "first": dates[0],
            "last": dates[-1],
            "source": source or "Red Hat security advisories (RHSA)",
            "tool": "rhsa.py " + VERSION,
        },
        "advisories": advisories,
        "cves": dict(cves),
    }


def load_index(path):
    if not os.path.exists(path):
        sys.exit("rhsa.py: no index at %s (build one with: rhsa.py index LIST --repo DIR)" % path)
    return json.load(open(path, encoding="utf-8"))


def recs(idx, cve):
    return [dict(rhsa=r, **idx["advisories"][r]) for r in idx["cves"].get(cve, [])]


def load_placement(path=PLACEMENT):
    p = json.load(open(path, encoding="utf-8"))
    return {k: v for k, v in p.items() if not k.startswith("_")}, p


def readmes(repo):
    for dp, dn, fn in os.walk(repo):
        if any(x in dp for x in SKIP_DIRS):
            continue
        for f in fn:
            if f == "README.md":
                yield os.path.relpath(os.path.join(dp, f), repo)


def repo_cves(repo):
    found = set()
    for rel in readmes(repo):
        found.update(re.findall(r"CVE-\d{4}-\d{4,7}", open(os.path.join(repo, rel), encoding="utf-8").read()))
    return found


def placed_cves(plc):
    s = set()
    for w in plc.values():
        s.update(w.get("cves", []))
        s.update(w.get("summary", []))
        s.update(w.get("point", {}))
    return s


# ---------- rendering ---------------------------------------------------------------------------------------
def rl(r):
    return "[%s](%s%s)" % (r, ERRATA, r)


def cl(c):
    return "[%s](%s%s)" % (c, CVEPAGE, c)


def sev(s):
    return s.capitalize()


def skey(s):
    m = re.match(r"RHEL (\d+)(?:\.(\d+))?$", s)
    return (0, int(m.group(1)), int(m.group(2) or -1), "") if m else (1, 0, 0, s)


def pk(items, limit=3, prefer=None):
    if prefer:
        items = sorted(items, key=lambda i: 0 if re.search(prefer, i["name"]) else 1)
    shown = []
    for i in items[:limit]:
        full = "%s-%s-%s" % (i["name"], i["ver"], i["rel"]) if i["ver"] and i["kind"] != "image" else i["name"]
        shown.append("`%s` (%s)" % (full, i["stream"]))
    if len(items) > limit:
        shown.append("and %d more" % (len(items) - limit))
    return "; ".join(shown)


def summary_line(c, rs):
    sv = collections.Counter(r["severity"] for r in rs)
    st = collections.Counter(
        i["stream"].split(".")[0] if i["stream"].startswith("RHEL") else i["stream"] for r in rs for i in r["items"][:1]
    )
    pkgs = collections.Counter(i["name"] for r in rs for i in r["items"][:1])
    return "%s: %d advisories, %s to %s; %s; by stream, %s; most often %s. All of them: [Red Hat's CVE page](%s%s)." % (
        cl(c),
        len(rs),
        rs[0]["date"],
        rs[-1]["date"],
        ", ".join("%d %s" % (n, k) for k, n in sv.most_common()),
        ", ".join("%s %d" % (k, n) for k, n in sorted(st.items(), key=lambda kv: skey(kv[0]))),
        ", ".join("`%s` (%d)" % (k, n) for k, n in pkgs.most_common(4)),
        CVEPAGE,
        c,
    )


def kernel_section(idx, cves):
    streams, cell = set(), collections.defaultdict(list)
    for c in cves:
        for r in recs(idx, c):
            for st in {i["stream"] for i in r["items"]}:
                names = {i["name"] for i in r["items"] if i["stream"] == st}
                tag = " rt" if names == {"kernel-rt"} else " kp" if names == {"kpatch-patch"} else ""
                streams.add(st)
                cell[(st, c)].append(r["rhsa"].split(":")[1] + tag)
    rows = ["| Stream | " + " | ".join(c.replace("CVE-2026-", "") for c in cves) + " |", "|---|" + "---|" * len(cves)]
    for st in sorted(streams, key=skey):

        def one(c):
            ids = sorted(set(cell.get((st, c), [])))
            return "%d advisories" % len(ids) if len(ids) > 4 else ", ".join(ids)

        rows.append("| %s | " % st + " | ".join(one(c) for c in cves) + " |")
    out = [
        "The columns are CVE-2026-NNNNN. The table shows, for each stream, the advisories that name each CVE (the "
        "number is the part of RHSA-2026:NNNNN after the colon; `rt` is `kernel-rt`, `kp` is a `kpatch-patch` live "
        "patch). A blank cell means no advisory in the list, not that the stream is unaffected. Each advisory is "
        "at `%sRHSA-2026:NNNNN`." % ERRATA,
        "",
        *rows,
    ]
    k = [(r, i) for r in recs(idx, "CVE-2026-98432") for i in r["items"] if i["name"] == "kernel"]
    if k:
        out += [
            "",
            "The fixed kernels for CVE-2026-98432 (IPv4 TCP use-after-free), newest first. A kernel is fixed if "
            "its release is this one or a later one in the same stream:",
            "",
            "| Stream | Advisory | Released | Severity | Kernel |",
            "|---|---|---|---|---|",
        ]
        for r, i in sorted(k, key=lambda x: (skey(x[1]["stream"]), x[0]["date"])):
            out.append(
                "| %s | %s | %s | %s | `kernel-%s-%s` |"
                % (i["stream"], rl(r["rhsa"]), r["date"], sev(r["severity"]), i["ver"], i["rel"])
            )
    return out


def section(path, plc, idx):
    w = plc[path]
    m = idx["meta"]
    lines = [
        BEGIN,
        "## Red Hat advisories",
        "",
        "Red Hat's advisory list (security advisories released %s to %s) names the CVEs below. A Red Hat build is "
        "judged by its RPM release, not by the upstream version number, because Red Hat backports fixes: the "
        "advisory names the release that fixes it. A CVE with no advisory in the list has none for that period, "
        "which is not the same as not affected. The current state is on [Red Hat's CVE database](%s)."
        % (m["first"], m["last"], CVEDB),
        "",
    ]
    if w.get("note"):
        lines += [w["note"], ""]
    big, full = [], []
    for c in w.get("cves", []):
        rs = recs(idx, c)
        if not rs:
            continue
        if len(rs) > MANY and not w.get("matrix"):
            f = [r for r in rs if w.get("focus") and any(re.search(w["focus"], i["name"]) for i in r["items"])]
            big.append((c, rs))
            full += [(c, r) for r in f]
        else:
            full += [(c, r) for r in rs]
    if w.get("matrix"):
        lines += kernel_section(idx, w["cves"])
    elif full:
        by = collections.OrderedDict()
        for c, r in sorted(full, key=lambda x: (x[1]["date"], x[1]["rhsa"])):
            by.setdefault(r["rhsa"], (r, []))[1].append(c)
        lines += [
            "| Advisory | Released | Severity | Package and stream | CVEs on this page |",
            "|---|---|---|---|---|",
        ]
        for rhsa, (r, cs) in by.items():
            lines.append(
                "| %s | %s | %s | %s | %s |"
                % (rl(rhsa), r["date"], sev(r["severity"]), pk(r["items"], prefer=w.get("focus")), ", ".join(cs))
            )
    extra = [summary_line(c, rs) for c, rs in big] + [
        summary_line(c, recs(idx, c)) for c in w.get("summary", []) if c in idx["cves"]
    ]
    if extra:
        lines += ([] if lines[-1] == "" else [""]) + ["- " + x for x in extra]
    labels = {}
    for p, ww in plc.items():
        for c in ww.get("cves", []):
            labels.setdefault(c, ww.get("label") or p.split("/")[0])
    for c, target in sorted(w.get("point", {}).items()):
        if c in idx["cves"]:
            lines += [
                "",
                "%s: %d advisories, listed in the [Red Hat advisories section of the %s README](%s)."
                % (cl(c), len(idx["cves"][c]), labels.get(c, "other"), target),
            ]
    lines += ["", END]
    return "\n".join(lines) + "\n"


def document(idx, plc):
    m = idx["meta"]
    owner = {}
    for p, w in plc.items():
        for c in w.get("cves", []) + w.get("summary", []):
            owner.setdefault(c, p)

    def tool(p):
        return p.split("/README")[0] if p != "README.md" else "main"

    lines = [
        "# Red Hat advisories",
        "",
        "Red Hat publishes a security advisory (RHSA) for each fix it ships. This page lists the advisories that "
        "name a CVE this collection covers, taken from Red Hat's advisory list for security advisories released %s "
        "to %s (%d advisories for %d CVEs). Each tool README that has any carries the same data in its own **Red "
        "Hat advisories** section." % (m["first"], m["last"], m["advisories"], m["cves"]),
        "",
        "How to use it: a Red Hat build is judged by its RPM release, not by the upstream version number, because "
        "Red Hat backports fixes. Find your stream and compare the installed release (`rpm -q PACKAGE`) with the "
        "one the advisory names. A CVE with no advisory in the list has none for that period, which is not the "
        "same as not affected. The list holds security advisories only, not bug fixes or enhancements. The current "
        "state is always on Red Hat's own pages. On a Red Hat family host with the packages installed, "
        "`/opt/psf-security-patches/rhsa/rhsa.py verify --rpm` makes the comparison for every installed package "
        "(`man psf-rhsa`).",
        "",
        "## By tool",
        "",
        "| Tool | CVEs with an advisory | Advisories | First | Last |",
        "|---|---|---|---|---|",
    ]
    per = collections.defaultdict(list)
    for c, p in owner.items():
        if c in idx["cves"]:
            per[p].append(c)
    for p in sorted(per, key=tool):
        cs = sorted(per[p])
        rs = sorted({r for c in cs for r in idx["cves"][c]})
        ds = sorted(idx["advisories"][r]["date"] for r in rs)
        lines.append(
            "| [%s](%s#red-hat-advisories) | %d | %d | %s | %s |" % (tool(p), p, len(cs), len(rs), ds[0], ds[-1])
        )
    lines += [
        "",
        "## By CVE",
        "",
        "| CVE | Tool | Advisories | Highest severity | First | Last |",
        "|---|---|---|---|---|---|",
    ]
    for c in sorted(c for c in idx["cves"] if c in owner):
        rs = recs(idx, c)
        top = min((r["severity"] for r in rs), key=lambda s: SEVERITY_ORDER.get(s, 9))
        lines.append(
            "| %s | [%s](%s#red-hat-advisories) | %d | %s | %s | %s |"
            % (cl(c), tool(owner[c]), owner[c], len(rs), sev(top), rs[0]["date"], rs[-1]["date"])
        )
    lines += [
        "",
        "## Source and limits",
        "",
        "- The data is Red Hat's published advisory list, one record per advisory with its CVEs and its packages, "
        "released %s to %s. Regenerate this page and the README sections from a newer list with "
        "`packaging/rhsa/rhsa.py` (`fetch`, `index`, then `docs --write`; its README says how)."
        % (m["first"], m["last"]),
        "- Streams are read from the release of each package (`el8_10` is RHEL 8.10, `hum1` is a Hummingbird "
        "build), so a stream name here is a reading of a package name, not a statement by Red Hat.",
        "- Rebuilds of RHEL (AlmaLinux, Rocky Linux, Oracle Linux) publish their own advisories and kernels; they "
        "follow Red Hat's fixes but not on the same day or with the same ids.",
        "",
    ]
    return "\n".join(lines)


def apply_block(path, new, check):
    cur = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
    mb = BEGIN_RE.search(cur)
    if mb and END in cur:
        out = cur[: mb.start()] + new + cur[cur.index(END) + len(END) + 1 :]
    else:
        m = list(FOOTER_RE.finditer(cur))
        i = m[-1].start() + 1 if m else len(cur)
        out = cur[:i] + new + "\n" + cur[i:]
    if out != cur:
        if not check:
            open(path, "w", encoding="utf-8").write(out)
        return True
    return False


